import numpy as np, pandas as pd, pipeline_energia as P
df = P.cargar(); X, y = P.construir(df, expost=True)
pd.set_option("display.width", 220)
print("Horas:", len(df), "| desde", df.index.min(), "hasta", df.index.max())
print(y.describe().round(1))
a = y.resample("YE").agg(["mean", "max", "sum"]); a["sum"] /= 1e3; print("Por año (MWh/h media, pico, GWh):\n", a.round(1))
print("Crecimiento demanda media 2021→2025: %.1f %%" % (100*(y["2025"].mean()/y["2021"].mean()-1)))
perf = y.groupby([X.tipo_dia, X.hora]).mean().unstack(0).round(0); perf.columns = ["laboral", "sábado", "dom/festivo"]; print(perf.T)
print("Festivo vs laboral (misma hora, media): %.1f %%" % (100*(y[X.festivo == 1].mean()/y[(X.festivo == 0) & (X.dow < 5)].mean()-1)))
# relación con el calor: demanda media por tramo de índice de calor (hora 14-16)
m = X.hora.between(13, 16) & (X.tipo_dia == 0)
b = pd.cut(X.calor[m], [20, 30, 34, 38, 42, 46, 60])
print("Laboral 13-16 h, demanda media por índice de calor (°C):\n", y[m].groupby(b).agg(["mean", "count"]).round(0))
r = y.groupby(y.index.normalize()).mean(); t = df.T2M.groupby(df.index.normalize()).max()
print("Corr. demanda diaria vs T máx del día: %.3f | vs T máx del día anterior: %.3f" % (r.corr(t), r.corr(t.shift(1))))
print("Autocorrelación horaria rezago 24h: %.3f | 168h: %.3f" % (y.autocorr(24), y.autocorr(168)))
print("Faltantes clima (interpolados):", df[["T2M", "RH2M"]].isna().sum().to_dict())
